"""Subject-level intervals and paired contrasts for the matched-input terms,
plus raw-versus-scaled calibration on BCI IV-2a.

The matched-input term for an architecture is narrowband minus broadband
held-out accuracy. Each term gets a percentile bootstrap interval over
subjects, and each pair of architectures is contrasted within subject (term A
minus term B, two-sided Wilcoxon, Benjamini-Hochberg over the three pairs).

Outputs results/paper_calibration_stats/fm_audit/matched_input_contrasts.md.
"""
from __future__ import annotations

from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

DATASET = "bci4_2a"
N_BOOT = 10_000
SEED = 0
SOTA = Path("results") / "supervised_sota"
OUT = Path("results") / "paper_calibration_stats" / "fm_audit" / "matched_input_contrasts.md"

# architecture -> (narrowband csv, broadband csv)
ARMS = {
    "atcnet": (SOTA / "supervised_atcnet_narrowband_tuned_subject_metrics.csv",
               SOTA / "supervised_atcnet_broadband_tuned_subject_metrics.csv"),
    "shallow_convnet": (SOTA / "supervised_shallow_convnet_narrowband_tuned_subject_metrics.csv",
                        Path("results/fm_probe/fm_probe_supervised_broadband_tuned_subject_metrics.csv")),
    "eegconformer": (SOTA / "supervised_eegconformer_narrowband_tuned_subject_metrics.csv",
                     SOTA / "supervised_eegconformer_broadband_tuned_subject_metrics.csv"),
}

# label -> (csv, experiment_key)
CALIBRATION = {
    "ATCNet, broadband": (ARMS["atcnet"][1], "atcnet_broadband_tuned"),
    "ShallowConvNet, broadband": (ARMS["shallow_convnet"][1], "shallow_convnet_broadband_tuned"),
    "EEG Conformer, broadband": (ARMS["eegconformer"][1], "eegconformer_broadband_tuned"),
    "CBraMod, fine-tuned": ("results/fm_probe/fm_probe_cbramod_finetune_sel_subject_metrics.csv", "cbramod_finetune_sel"),
    "CBraMod, frozen": ("results/fm_probe_frozen_probs/fm_probe_cbramod_frozen_subject_metrics.csv", "cbramod_frozen_p2"),
    "CBraMod, random init.": ("results/fm_probe/fm_probe_cbramod_finetune_randinit_sel_subject_metrics.csv", "cbramod_finetune_randinit_sel"),
    "LaBraM, frozen": ("results/fm_probe_frozen_probs/fm_probe_frozen_subject_metrics.csv", "labram_frozen_p2"),
}


def load(path, key=None) -> pd.DataFrame:
    d = pd.read_csv(path)
    if d["eval_labels_used_for_selection"].astype(bool).any():
        raise SystemExit(f"{path}: held-out labels used for selection")
    d = d[d["dataset"] == DATASET]
    if key is not None:
        d = d[d["experiment_key"] == key]
    return d.set_index("subject").sort_index()


def bh(p: list[float]) -> np.ndarray:
    p = np.asarray(p, dtype=float)
    order = np.argsort(p)
    scaled = p[order] * len(p) / np.arange(1, len(p) + 1)
    adj = np.minimum.accumulate(scaled[::-1])[::-1]
    out = np.empty_like(p)
    out[order] = np.minimum(adj, 1.0)
    return out


def boot_ci(x: np.ndarray, rng) -> tuple[float, float]:
    idx = rng.integers(0, len(x), (N_BOOT, len(x)))
    lo, hi = np.percentile(x[idx].mean(axis=1), [2.5, 97.5])
    return float(lo), float(hi)


def main() -> None:
    rng = np.random.default_rng(SEED)
    lines = ["# Matched-input contrasts and calibration", "",
             "Generated by `src/scripts/make_matched_input_contrasts.py`. Do not edit by hand.", "",
             "## Matched-input terms (narrowband minus broadband accuracy)", "",
             "| arch | n | term | ci_lo | ci_hi | narrow_wins |", "|---|---|---|---|---|---|"]
    terms = {}
    for arch, (narrow, broad) in ARMS.items():
        d = (load(narrow)["heldout_accuracy"] - load(broad)["heldout_accuracy"]).dropna()
        terms[arch] = d
        lo, hi = boot_ci(d.to_numpy(), rng)
        lines.append(f"| {arch} | {len(d)} | {d.mean():.4f} | {lo:.3f} | {hi:.3f} | {(d > 0).sum()}/{len(d)} |")

    pairs = list(combinations(ARMS, 2))
    raw_p, rows = [], []
    for a, b in pairs:
        dd = (terms[a] - terms[b]).dropna()
        raw_p.append(wilcoxon(dd).pvalue)
        rows.append((a, b, dd, *boot_ci(dd.to_numpy(), rng)))
    p_bh = bh(raw_p)
    lines += ["", "## Paired contrasts between architecture-specific terms", "",
              "| a | b | n | a_minus_b | ci_lo | ci_hi | a_wins | p_raw | p_bh |", "|---|---|---|---|---|---|---|---|---|"]
    for (a, b, dd, lo, hi), p, q in zip(rows, raw_p, p_bh):
        lines.append(f"| {a} | {b} | {len(dd)} | {dd.mean():.4f} | {lo:.3f} | {hi:.3f} | "
                     f"{(dd > 0).sum()}/{len(dd)} | {p:.4f} | {q:.4f} |")

    lines += ["", "## Calibration before and after temperature scaling", "",
              "ECE is top-label over 15 equal-mass bins (`evaluate.compute_ece`). Raw NLL is not stored.", "",
              "| configuration | Brier_raw | Brier_scaled | ECE_raw | ECE_scaled | ci_lo | ci_hi | NLL_scaled | T |",
              "|---|---|---|---|---|---|---|---|---|"]
    for label, (path, key) in CALIBRATION.items():
        d = load(path, key)
        lo, hi = boot_ci(d["heldout_ECE"].to_numpy(), rng)
        lines.append(f"| {label} | {d['heldout_Brier_uncalibrated'].mean():.4f} | {d['heldout_Brier'].mean():.4f} | "
                     f"{d['heldout_ECE_uncalibrated'].mean():.4f} | {d['heldout_ECE'].mean():.4f} | {lo:.3f} | {hi:.3f} | "
                     f"{d['heldout_NLL'].mean():.4f} | {d['temperature'].mean():.3f} |")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
